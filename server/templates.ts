export function buildRaci(processes: Process[]): ResponsibilityAssignment[] {
  const out: ResponsibilityAssignment[] = [];
  const phases: PhaseId[] = ["report", "assess", "respond", "recover", "close"];
  const table: Record<string, string> = {
    "r-reporter": "RIIII",
    "r-first": "ARCCI",
    "r-lead": "IARRC",
    "r-security": "IARRC",
    "r-privacy": "CARCI",
    "r-facilities": "IARRC",
    "r-safety": "IARRC",
    "r-hr": "IARRC",
    "r-bcm": "ICARC",
    "r-irt": "ICACA",
    "r-crt": "IICIA",
    "r-comms": "IICII",
  };
  for (const p of processes)
    for (const r of p.roleIds)
      phases.forEach((ph, i) =>
        out.push({
          id: `${p.id}-${r}-${ph}`,
          processId: p.id,
          roleId: r,
          phase: ph,
          value: (table[r] ?? "IIIII")[i] as "R",
        }),
      );
  return out;
}

