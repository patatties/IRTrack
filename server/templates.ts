export function buildSituations(now: Date): GuidanceSituation[] {
  return SITS.map((s, i) => {
    const flow =
      s.flowchart ??
      genericFlow(
        "Is anyone in immediate danger?",
        s.doFirst[0],
        "Contact the responsible team",
        s.contactIds[0],
        "Escalate to the specialist lead",
        "r-lead",
      );
    const reviewDate = addDays(now, 180).toISOString();
    const { slug, overdue: _o, flowchart: _f, keywords, ...rest } = s;
    const content: GuidanceContent = {
      ...rest,
      keywords: keywords.split(" "),
      owner: "Incident Management",
      reviewDate,
      flowchart: flow,
    };
    return {
      id: `s-${i + 1}`,
      slug,
      versions: [
        {
          version: 1,
          status: "published",
          savedAt: now.toISOString(),
          savedBy: "template",
          content,
        },
      ],
    };
  });
}

